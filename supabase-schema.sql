create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null,
 description text default '',
 price numeric(12,2) not null default 0,
 old_price numeric(12,2) not null default 0,
 image_url text default '',
 category text not null default 'all',
 stock integer not null default 0,
 tag text default '',
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(),
 customer_name text not null,
 customer_email text not null,
 customer_phone text not null,
 shipping_cep text not null,
 shipping_address text not null,
 shipping_number text not null,
 shipping_complement text default '',
 items jsonb not null,
 total numeric(12,2) not null default 0,
 status text not null default 'pending_payment',
 payment_preference_id text,
 payment_id text,
 created_at timestamptz not null default now()
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
drop policy if exists "Produtos ativos visíveis publicamente" on public.products;
create policy "Produtos ativos visíveis publicamente" on public.products for select to anon,authenticated using (active=true);
drop policy if exists "Admin gerencia produtos" on public.products;
create policy "Admin gerencia produtos" on public.products for all to authenticated using ((auth.jwt()->'app_metadata'->>'role')='admin') with check ((auth.jwt()->'app_metadata'->>'role')='admin');
drop policy if exists "Cliente registra pedido" on public.orders;
create policy "Cliente registra pedido" on public.orders for insert to anon,authenticated with check (status='pending_payment');
drop policy if exists "Admin consulta pedidos" on public.orders;
create policy "Admin consulta pedidos" on public.orders for select to authenticated using ((auth.jwt()->'app_metadata'->>'role')='admin');
